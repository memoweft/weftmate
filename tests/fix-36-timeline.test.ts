import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {progressEvents,timelineCore} from './helpers/fix-36-timeline.mjs';
const core:any=timelineCore();
test('FIX-36 twelve tool steps become one row below the completed reply',()=>{
  const rows=core.nativeTimelineRows(progressEvents()),progress=rows.filter(row=>row.type==='native.progress');
  assert.equal(progress.length,1);assert.equal(progress[0].data.steps.length,12);
  assert.equal(rows.at(-1).type,'native.progress');assert.equal(rows.at(-2).type,'assistant.message');
  assert.match(progress[0].data.summary,/查了健康数据.*查了日历/);assert.doesNotMatch(progress[0].data.summary,/准备可用工具|调用扩展服务/);
  assert.ok(progress[0].data.steps.every(step=>!step.summary.includes('调用扩展服务')));
  assert.ok(core.projectTimeline(progressEvents()).groups.flatMap(group=>group.steps).every(step=>!step.summary.includes('调用扩展服务')));
});
test('FIX-36 running summary shows only the changing current step',()=>{
  const events=progressEvents('running');let row=core.nativeTimelineRows(events).find(row=>row.type==='native.progress');
  assert.equal(row.data.summary,'正在读取邮件…');assert.equal(row.data.running,true);
  events.at(-1).data.toolName='mcp__calendar__calendar_list_events';
  row=core.nativeTimelineRows(events).find(row=>row.type==='native.progress');assert.equal(row.data.summary,'正在查询日历…');
});
test('FIX-36 failed and pending approval steps remain visible and approval card is independent',()=>{
  const failed=core.nativeTimelineRows(progressEvents('failed')).find(row=>row.type==='native.progress');
  assert.equal(failed.data.steps.filter(step=>step.attention).length,1);assert.equal(failed.data.failed,true);
  const rows=core.nativeTimelineRows(progressEvents('approval'),[{approvalId:'synthetic-approval',callId:'step-11',turn:1,status:'pending'}]);
  assert.equal(rows.filter(row=>row.type==='approval.requested').length,1);
  assert.equal(rows.find(row=>row.type==='native.progress').data.steps.filter(step=>step.attention).length,1);
});
test('FIX-36 same turn number in two source sessions never combines replies',()=>{
  const events=[...progressEvents('completed','a'),...progressEvents('completed','b')].map(({sessionId,...event})=>event);
  const rows=core.nativeTimelineRows(events);
  assert.equal(rows.filter(row=>row.type==='native.progress').length,2);
  assert.equal(rows.at(-1).sourceRef.sessionId,'b');
});
test('FIX-36 a resolved approval snapshot clears pending attention in a logical source session',()=>{
  const approval={approvalId:'synthetic-approval',callId:'step-11',sessionId:'synthetic-session',taskId:'command-one',turn:1,status:'resolved',outcome:'allowed-once'};
  const progress=core.nativeTimelineRows(progressEvents('approval'),[approval]).find(row=>row.type==='native.progress');
  assert.equal(progress.data.steps.at(-1).approvalStatus,'resolved');assert.equal(progress.data.steps.at(-1).attention,false);
  assert.equal(progress.data.steps.at(-1).approvalText,'已批准');
});
test('FIX-36 desktop tool blocks retain chronology across completed and running turns',()=>{
  const first=progressEvents(),second=progressEvents('running','synthetic-session',2).map((event,index)=>({...event,seq:first.length+index+1}));
  const events=[...first,...second],blocks=core.projectTimeline(events).groups;
  assert.equal(core.progressPosition(events,blocks[0]),blocks[0].seq);
  assert.equal(core.progressPosition(events,blocks.at(-1)),blocks.at(-1).seq);
  assert.equal(core.nativeTimelineRows(events).filter(row=>row.type==='native.progress').length,2);
});
test('FIX-36 native JVM fixture is generated by the same shared timeline code',()=>{
  const fixture=JSON.parse(readFileSync('apps/android/app/src/test/resources/fix36-progress.json','utf8'));
  for(const mode of ['completed','running','failed','approval']) assert.deepEqual(fixture[mode],JSON.parse(JSON.stringify(core.nativeTimelineRows(progressEvents(mode)))));
});
