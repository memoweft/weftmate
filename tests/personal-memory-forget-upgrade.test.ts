import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { createServer } from 'node:http';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import test from 'node:test';
import { createMemoryActions } from '../src/personal-memory/actions.mjs';
import { scopedForgetPlan, checkForgetCompletion } from '../src/personal-memory/forget-model.mjs';

const owner = 'synthetic-upgrade-owner';
const scope = { authorized: true, subject: 'self', topic: '我喝茶的偏好' };
const request = { requestId: 'upgrade-forget', name: 'memory_forget', scope,
  arguments: { query: scope.topic }, source: { text: '请忘掉我喝茶的偏好。' } };
// Generated by the actual scopedForgetPlan at 84e341f from the same fixture.
// Its source module and generation trace are retained with the review evidence.
const oldPlan = { version: 2, worldRevision: 7, authorizedEvidenceIds: ['green-source'], evidenceIds: [],
  sourceTexts: ['用户喝茶的偏好是绿茶。'], worldTargets: [{ kind: 'cognition', id: 'green' }],
  affectedIds: ['green'], authorization: scope, retainedOtherCount: 0, retainedUncertainCount: 0 };

async function fixture(t: any, mode: 'self-mixed' | 'other-mixed' | 'other-only' | 'safe' | 'unknown' | 'both-targets' = 'self-mixed',
  malformed?: 'missing' | 'contradictory') {
  const root = await mkdtemp(join(tmpdir(), 'weftmate-forget-upgrade-'));
  let revision = 7;
  const commands: any[] = [], receipts = new Map(), decisions: any[] = [];
  const permissions = { allow_inference: true, allow_cloud_read: true, allow_local_read: true };
  const source = (id: string, text: string) => ({ evidence_id: id, raw_content: text, summary: text, content_available: true, permissions });
  const mixed = mode === 'self-mixed' ? '用户喝茶的偏好是红茶。我周末喜欢散步。'
    : mode === 'safe' ? '我周末喜欢散步。' : mode === 'other-only' ? '另一位家人喜欢喝红茶。'
    : mode === 'unknown' ? '有人喜欢喝红茶。我周末喜欢散步。'
    : mode === 'both-targets' ? '另一位家人喜欢喝红茶。用户喝茶的偏好也是红茶。' : '另一位家人喜欢喝红茶。我周末喜欢散步。';
  const sources = new Map([['green-source', source('green-source', '用户喝茶的偏好是绿茶。')], ['mixed-source', source('mixed-source', mixed)]]);
  const cognition = (id: string, content: string, evidence: string, target?: string) => ({ item_id: id, object_kind: 'cognition',
    current_state: 'current', value: { content, ...(target ? { target_entity_id: target } : {}) },
    provenance: [{ evidence_id: evidence, evidence: sources.get(evidence), permissions }] });
  let rows: any[] = [cognition('green', '用户喝茶的偏好是绿茶。', 'green-source'),
    ...(mode === 'other-mixed' || mode === 'other-only' ? [cognition('other-tea', '另一位家人喜欢喝红茶。', 'mixed-source', 'relative'),
      { item_id: 'relative', object_kind: 'entity', value: { kind: 'person', canonical_name: '另一位家人' }, provenance: [] }] : []),
    ...(mode !== 'other-only' ? [cognition('walking', '用户周末喜欢散步。', 'mixed-source')] : [])];
  const server = createServer(async (req, res) => {
    let text = ''; for await (const part of req) text += part;
    const body = JSON.parse(text), input = JSON.parse(body.messages.at(-1).content), schema = body.tools[0].function.parameters.properties.items.items.properties;
    decisions.push(input);
    const items = input.candidates.map((candidate: any) => {
      const evidence = candidate.key === 'evidence:mixed-source';
      const targetFact = evidence ? mode !== 'safe' : candidate.text.includes('茶');
      const targetSubjects = !targetFact ? [] : candidate.key.includes('green') ? ['self'] : mode === 'both-targets' ? ['other:另一位家人', 'self']
        : mode === 'unknown' ? ['unknown'] : mode.startsWith('other') ? ['other:另一位家人'] : ['self'];
      const subjects = evidence && mode === 'other-mixed' || mode === 'both-targets' && targetFact && !candidate.key.includes('green')
        ? ['other:另一位家人', 'self'] : targetFact ? targetSubjects : ['self'];
      return { key: candidate.key, matchesTopic: targetFact, hasTargetFact: targetFact, subjects,
        ...(schema.targetSubjects && malformed !== 'missing' ? { targetSubjects: malformed === 'contradictory' ? ['other:unmentioned'] : targetSubjects } : {}),
        sourceFullyAuthorized: !candidate.sourceTexts.includes(mixed) };
    });
    res.end(JSON.stringify({ choices: [{ finish_reason: 'tool_calls', message: { tool_calls: [{ function: {
      name: body.tools[0].function.name, arguments: JSON.stringify({ items }) } }] } }] }));
  });
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  const route = { baseUrl: `http://127.0.0.1:${(server.address() as any).port}`, model: 'synthetic', credential: 'synthetic', modelTier: 'cloud' };
  const manager: any = {
    async revalidateForget(_owner: string, action: any) { return action.scope ?? action.plan?.authorization; },
    async query(account: string, method: string, params: any) {
      assert.equal(account, owner);
      if (method === 'query_world') return { world_revision: revision, items: rows.filter(row => row.object_kind === params.object_kind) };
      if (method === 'query_evidence') return { world_revision: revision, evidence: sources.get(params.evidence_id) };
      if (method === 'preview_recall') return { preview: { recent_evidence: [], pending_corrections: [] } };
      if (method === 'query_jobs') return { formation_requests: [] };
      if (method === 'preview_forget') return { world_revision: revision,
        items: rows.filter(row => row.item_id === params.target_id).map(row => ({ ...row, name: row.value.content })), evidence_ids: ['green-source'] };
      throw Error(method);
    },
    async planForget(account: string, action: any) { return scopedForgetPlan(manager, account, action, route); },
    async submitCommand(account: string, command: any) {
      assert.equal(account, owner); commands.push(structuredClone(command)); const before = revision++;
      rows = rows.filter(row => row.item_id !== 'green'); sources.delete('green-source');
      const result = { receipt: { command_id: command.requestId, result_state: 'applied', before_revision: before, after_revision: revision } };
      receipts.set(command.requestId, result); return result;
    },
    async receiptForAction(account: string, command: any) { assert.equal(account, owner); return receipts.get(command.requestId); }
  };
  const actions = createMemoryActions({ root, manager: () => manager, schedule() {} });
  const file = join(root, 'accounts', owner, 'memory-home', 'pending-actions.json');
  async function seed(extra = {}) { await mkdir(dirname(file), { recursive: true }); await writeFile(file, JSON.stringify({ records: {
    [request.requestId]: { ...request, plan: structuredClone(oldPlan), ...extra } } })); }
  t.after(async () => { await actions.close(); server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve())); await rm(root, { recursive: true, force: true }); });
  return { actions, manager, route, seed, commands, receipts, sources, mixed, decisions, file, get revision() { return revision; } };
}

test('an authentic old v2 plan is rechecked before dispatch without replacing its frozen scope', async t => {
  const f = await fixture(t); await f.seed();
  const result = await f.actions.submit(owner, request);
  assert.equal(result.state, 'withheld'); assert.equal(f.commands.length, 0); assert.equal(f.revision, 7);
  assert.equal(f.sources.get('mixed-source').raw_content, f.mixed);
  assert.equal((await f.actions.submit(owner, request)).state, 'withheld'); assert.equal(await f.actions.pending(owner), false);
});

test('an old plan with a matched applied receipt stops as partial without replay or scope replacement', async t => {
  const f = await fixture(t), command = { requestId: 'old-stable-command', operation: 'delete_world_item', targetKind: 'cognition', targetId: 'green', expectedWorldRevision: 7, payload: {} };
  const receipt = await f.manager.submitCommand(owner, command), original = structuredClone(receipt);
  await f.seed({ commands: { 'cognition:green': command }, finished: ['cognition:green'] });
  assert.equal((await f.actions.submit(owner, request)).state, 'partial');
  assert.match((await f.actions.submit(owner, request)).message, /原请求已执行.*不能确认完全忘掉/);
  assert.equal(f.commands.length, 1); assert.deepEqual(f.receipts.get(command.requestId), original); assert.equal(f.revision, 8);
  assert.equal(f.decisions.length, 0, 'An existing legacy command is settled only from its original receipt');
});

test('an old plan with an unknown original command never dispatches or claims nonexecution', async t => {
  const f = await fixture(t), command = { requestId: 'old-unconfirmed-command', operation: 'delete_world_item', targetKind: 'cognition', targetId: 'green', expectedWorldRevision: 7, payload: {} };
  await f.seed({ commands: { 'cognition:green': command } });
  const result = await f.actions.submit(owner, request);
  assert.equal(result.state, 'queued'); assert.match(result.message, /未能确认|待确认/); assert.doesNotMatch(result.message, /没有执行遗忘|没有删除记忆/);
  assert.equal(f.commands.length, 0); assert.equal(f.revision, 7);
  const pending = JSON.parse(await readFile(f.file, 'utf8')).records[request.requestId];
  assert.deepEqual(pending.commands['cognition:green'], command); assert.deepEqual(pending.plan.worldTargets, oldPlan.worldTargets);
  assert.equal(pending.plan.worldRevision, oldPlan.worldRevision);
  assert.equal(f.decisions.length, 0);
  await f.manager.submitCommand(owner, command); await f.actions.resume(owner);
  assert.equal((await f.actions.submit(owner, request)).state, 'partial'); assert.equal(f.commands.length, 1);
});

test('old safe plans keep the exact frozen deletion and original revision', async t => {
  const f = await fixture(t, 'safe'); await f.seed();
  assert.equal((await f.actions.submit(owner, request)).state, 'applied'); assert.equal(f.commands.length, 1);
  assert.equal(f.commands[0].targetId, 'green'); assert.equal(f.commands[0].expectedWorldRevision, 7);
  assert.equal(f.commands[0].requestId, 'forget:' + createHash('sha256').update(`${request.requestId}|cognition:green|7`).digest('hex'));
});

for (const mode of ['other-only', 'other-mixed'] as const) test(`target fact attribution preserves ${mode} source without blocking self deletion`, async t => {
  const f = await fixture(t, mode);
  const plan = await f.manager.planForget(owner, request);
  assert.equal(plan.retainedUncertainCount, 0);
  const page = await checkForgetCompletion(f.manager, owner, { targetKind: 'cognition', targetId: 'green', expectedWorldRevision: 7 }, f.route);
  assert.equal(page.state, 'complete');
  assert.equal((await f.actions.submit(owner, request)).state, 'applied'); assert.equal(f.commands.length, 1);
  assert.equal(f.sources.get('mixed-source').raw_content, f.mixed);
});

test('unclear target fact ownership remains withheld even alongside an unrelated self fact', async t => {
  const f = await fixture(t, 'unknown');
  assert.equal((await f.actions.submit(owner, request)).state, 'withheld');
  assert.equal((await checkForgetCompletion(f.manager, owner, { targetKind: 'cognition', targetId: 'green', expectedWorldRevision: 7 }, f.route)).state, 'withheld');
  assert.equal(f.commands.length, 0); assert.equal(f.revision, 7);
});

test('a source with target facts about both people cannot be dismissed as other-only', async t => {
  const f = await fixture(t, 'both-targets');
  assert.equal((await f.actions.submit(owner, request)).state, 'withheld');
  assert.equal((await checkForgetCompletion(f.manager, owner, { targetKind: 'cognition', targetId: 'green', expectedWorldRevision: 7 }, f.route)).state, 'withheld');
  assert.equal(f.commands.length, 0); assert.equal(f.revision, 7);
});

for (const malformed of ['missing', 'contradictory'] as const) test(`${malformed} target-fact attribution cannot fall back to source subjects`, async t => {
  const f = await fixture(t, 'other-mixed', malformed);
  const result = await f.actions.submit(owner, request);
  assert.notEqual(result.state, 'applied'); assert.equal(f.commands.length, 0); assert.equal(f.revision, 7);
  assert.equal((await checkForgetCompletion(f.manager, owner, { targetKind: 'cognition', targetId: 'green', expectedWorldRevision: 7 }, f.route)).state, 'withheld');
});

test('an upgraded proof cannot authorize newly nominated deletion targets', async t => {
  const f = await fixture(t, 'safe'); await f.seed();
  const planForget = f.manager.planForget;
  f.manager.planForget = async (account: string, action: any) => {
    assert.deepEqual(action.scope, oldPlan.authorization);
    const proof = await planForget(account, action);
    return { ...proof, worldTargets: [...proof.worldTargets, { kind: 'cognition', id: 'later-target' }] };
  };
  assert.equal((await f.actions.submit(owner, request)).state, 'withheld');
  assert.equal(f.commands.length, 0); assert.equal(f.revision, 7);
});

test('an old plan cannot adopt a later proof revision', async t => {
  const f = await fixture(t, 'safe'); await f.seed();
  const planForget = f.manager.planForget;
  f.manager.planForget = async (account: string, action: any) => ({ ...await planForget(account, action), worldRevision: 8 });
  assert.equal((await f.actions.submit(owner, request)).state, 'withheld');
  assert.equal(f.commands.length, 0); assert.equal(f.revision, 7);
});
