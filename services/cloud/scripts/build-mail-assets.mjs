// Run from the repository root; uses the existing development-only Playwright.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
import { fileURLToPath } from 'node:url';

const tokens = JSON.parse(await readFile(new URL('../../../design/tokens/tokens.json', import.meta.url), 'utf8'));
const css = await readFile(new URL('../../../src/personal-access-ui/tokens.css', import.meta.url), 'utf8');
const palette = selector => {
  const block = css.match(selector)[1];
  return Object.fromEntries(['canvas', 'surface', 'ink', 'ink-secondary', 'ink-muted', 'line'].map(key => [key, block.match(new RegExp(`--${key}: ([^;]+);`))[1]]));
};
const snapshot = {
  light: palette(/:root \{(\s*--canvas:[\s\S]*?)\n\}/),
  dark: palette(/:root\[data-theme="dark"\] \{([\s\S]*?)\n\}/),
  ...Object.fromEntries(Object.entries({
    space: ['4', '8', '12', '16', '20', '24', '28', '32', '36'],
    radius: ['12', '16'], fontSize: ['10', '13', '15', '27', '36'],
    fontFamily: ['body'], lineHeight: ['1_25', '1_65'],
  }).map(([key, names]) => [key, Object.fromEntries(names.map(name => [name, tokens.shared[key][name]]))])),
};
await writeFile(new URL('../src/mail-tokens.mjs', import.meta.url), `// Generated by services/cloud/scripts/build-mail-assets.mjs from the desktop design tokens.\nexport const mailTokens = ${JSON.stringify(snapshot, null, 2)};\n`);
await mkdir(new URL('../assets/', import.meta.url), { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 128, height: 128 }, deviceScaleFactor: 1 });
  const svg = await readFile(new URL('../../../src/personal-access-ui/favicon.svg', import.meta.url), 'utf8');
  await page.setContent(`<body style="margin:0;background:#fff">${svg.replace('<svg ', '<svg width="128" height="128" ')}</body>`);
  await page.screenshot({ path: fileURLToPath(new URL('../assets/weftmate-mark.png', import.meta.url)) });
} finally { await browser.close(); }
