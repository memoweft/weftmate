// Discover routes from the shipped interface and client contract. JVM tests feed
// these examples through the actual Android adapter and Kotlin allowlist.
import { readFile, readdir } from 'node:fs/promises';
import { resolve, relative } from 'node:path';
import { pathToFileURL } from 'node:url';
import { runInNewContext } from 'node:vm';

const root = resolve(import.meta.dirname, '..');
const uuid = '00000000-0000-4000-8000-000000000001';
export function exampleRoute(template) {
  return template.replace(/\$\{[^}]*\}|\{[^}]*\}|:[A-Za-z][A-Za-z0-9_]*/g, match =>
    /day/.test(match) ? '2026-10-12' : /seq/.test(match) ? '1' : /approval|question|device|request/i.test(match) ? uuid : 'sample-one')
    .replace(/YYYY-MM-DD/g, '2026-10-12').replace(/YYYY-MM/g, '2026-10')
    .replace(/model-services\/sample-one(?=\/|$)/, 'model-services/model-service-' + uuid)
    .replace(/health\/metrics\/sample-one/, 'health/metrics/sleep')
    .replace(/health\/suggestions\/sample-one/, 'health/suggestions/health-' + 'a'.repeat(32));
}
async function files(directory) {
  const rows = await readdir(directory, { withFileTypes: true });
  return (await Promise.all(rows.map(row => row.isDirectory() ? files(resolve(directory, row.name)) : resolve(directory, row.name)))).flat();
}
export async function inventory() {
  const routes = new Map();
  const add = (template, source, method = 'GET', cloudClient = false) => {
    if (template.includes('${kind}') && template.includes('${p[key]') && template.startsWith('/personal/v1/sessions/')) {
      for (const kind of ['approvals','questions']) {
        const base = template.replace('${kind}', kind).replace(/\$\{p\[key\][^}]*\}/, '');
        add(base, source, 'GET', cloudClient); add(base + '/' + uuid, source, 'POST', cloudClient);
      }
      return;
    }
    const branch = template.match(/\$\{[^}]*\?\s*'([^']*)'\s*:\s*'([^']*)'\}/);
    if (branch) { for (const value of [branch[1],branch[2]]) add(template.replace(branch[0], value), source, method, cloudClient); return; }
    if (cloudClient && /\$\{(?:auth\.mode|mode)[^}]*\}/.test(template)) {
      for (const mode of ['registration','recovery']) add(template.replace(/\$\{(?:auth\.mode|mode)[^}]*\}/, mode), source, method, true);
      return;
    }
    template = template.split('?')[0];
    if (template.includes('|')) { for (const part of template.split('|')) add(part.startsWith('/') ? part : template.slice(0, template.lastIndexOf('/') + 1) + part, source, method); return; }
    template = template.replace(/([^/])\$\{.*$/, '$1');
    // Queries generated by URLSearchParams are checked with concrete examples
    // in BusinessRouteUnitTest. Here every path family must be accounted for.
    const path = exampleRoute(template).replace(/\/$/, '/sample-one');
    if (/^\/personal\/v1\/(auth|cloud|account)$/.test(path) || /^\/personal\/v1\/(status|system)\./.test(path)) return;
    if (!path.startsWith('/personal/v1/') || /[\s`${}]/.test(path)) return;
    const key = method + ' ' + path;
    const row = routes.get(key) || { path, method, sources: [] };
    if (cloudClient) row.cloudClient = true;
    if (!row.sources.includes(source)) row.sources.push(source);
    routes.set(key, row);
  };
  for (const file of [...await files(resolve(root, 'src/ui-core')), ...await files(resolve(root, 'apps/mobile-ui/www'))]) {
    if (!file.endsWith('.js') || /vendor|icons|[\\/]ui-core[\\/]/.test(relative(resolve(root, 'apps/mobile-ui/www'), file)) && file.startsWith(resolve(root, 'apps/mobile-ui/www'))) continue;
    const source = relative(root, file).replaceAll('\\', '/'), text = await readFile(file, 'utf8');
    for (const match of text.matchAll(/(?:accessApi|memoryRequest|api)\(\s*(['"`])(\/[^\n]*?)\1/g)) {
      const prefix = match[0].startsWith('memoryRequest') ? '/personal/v1/memory' : match[0].startsWith('api(') ? '/personal/v1/auth' : '/personal/v1';
      const method = text.slice(match.index + match[0].length, match.index + match[0].length + 160).match(/method\s*:\s*['"](GET|POST|PATCH|PUT|DELETE)['"]/)?.[1] || 'GET';
      add(prefix + match[2], source, method);
    }
    for (const match of text.matchAll(/(['"`])(\/personal\/v1\/[^\n]*?)\1/g)) add(match[2], source);
    for (const match of text.matchAll(/(publicRequest|authorized)\(\s*(['"`])(\/[^\n]*?)\2/g)) {
      const options = text.slice(match.index + match[0].length, match.index + match[0].length + 160);
      const method = match[1] === 'publicRequest' ? 'POST' : options.match(/^\s*,\s*\{\s*method\s*:\s*['"](GET|POST|PATCH|PUT|DELETE)['"]/)?.[1] || 'GET';
      add('/personal/v1/cloud' + match[3], source, method, true);
    }
  }
  // These operations belong to the desktop/private host or binary transports;
  // they must never be enabled through the generic mobile business bridge.
  const excluded = [
    /^\/personal\/v1\/auth\//, /^\/personal\/v1\/cloud\//,
    /^\/personal\/v1\/ui(?:\/|$)/, /^\/personal\/v1\/app\//,
    /^\/personal\/v1\/push\//, /^\/personal\/v1\/sync\/events$/,
    /^\/personal\/v1\/sessions\/[^/]+\/attachments\//,
    /^\/personal\/v1\/models\/[^/]+\/(?:verify|chat\/completions)$/,
    /^\/personal\/v1\/library\/[^/]+\/(?:open|show)$/,
    /^\/personal\/v1\/(?:downloads|native)\//,
    /^\/personal\/v1\/(?:sync\/attachments|sync\/capabilities|sync\/conversations\/[^/]+\/local-turns)(?:\/|$)/,
    /^\/personal\/v1\/chats\/[^/]+\/attachments\//,
    /^\/personal\/v1\/artifacts\/[^/]+\/download$/,
    /^\/personal\/v1\/(?:onboarding|backups)(?:\/|$)/,
    /^\/personal\/v1\/models\/discover$/,
  ];
  const context = { URL, Map, Promise, Error, setTimeout, clearTimeout };
  runInNewContext(await readFile(resolve(root, 'src/ui-core/store.js'), 'utf8') + '\n' +
    await readFile(resolve(root, 'src/ui-core/adapters/android-bridge.js'), 'utf8'), context);
  let captured;
  const bridge = context.WeftUiCore.createAndroidBridge({ postMessage: text => {
    const message = JSON.parse(text); captured = message;
    queueMicrotask(() => bridge.receive({ id: message.id, ok: true, result: { source: 'host', sessions: [], models: [], activities: [], sessionId: message.params.sessionId } }));
  } });
  const result = [];
  for (const row of [...routes.values()].sort((a, b) => (a.path + a.method).localeCompare(b.path + b.method))) {
    if (row.cloudClient) { result.push({ ...row, transport:'cloud-account' }); continue; }
    if (excluded.some(rule => rule.test(row.path))) { result.push({ ...row, transport: 'specialized-or-desktop' }); continue; }
    captured = null;
    await bridge.fetch(row.path, { method: row.method, ...(row.method !== 'GET' ? { body: '{}' } : {}) });
    result.push({ ...row, transport: captured?.method === 'host.business' ? 'business' : captured?.method || 'unclassified' });
  }
  return result;
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const rows = await inventory();
  console.log(JSON.stringify(rows));
}
